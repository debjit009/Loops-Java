package AnujBhiya.Loops;

public class Loops_01 {
    public static void main(String[] args) {
        // System.out.println("Hello World!");
        // print 100 times --> Hello World using fo loop
        
        for(int i = 0;i<=100;i++){
            System.out.println("Hello World!");

        }
        for(int i = 0;i<=5;i++){
            System.out.println(i);
        }
    }
    
}

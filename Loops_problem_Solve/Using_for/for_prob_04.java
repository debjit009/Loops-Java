package Loops_problem_Solve.Using_for;

public class for_prob_04 {
    //--> print odd number 1-100
    public static void main(String[] args) {
        for(int i = 1;i<=100;i++){
            if(i%2!=0){
                System.out.println("The odd numbers are: "+i);
            }
        }
    }
    
}

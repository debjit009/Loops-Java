package Loops_problem_Solve.Using_for;

public class for_prob_05 {
    // 1-100 number sum calculate
    public static void main(String[] args) {
        int sum = 0;
        for(int i = 1;i<=20;i++){
            sum = sum+i;
            System.out.println("Sum is:" +sum);
        }
    }


    
    
    
}

package Loops_problem_Solve.Using_for;

public class for_prob_03 {
    public static void main(String[] args) {
        //---> print even number 1-20

        for(int i = 1;i<=20;i++){
            if(i%2==0){
                System.out.println("The even number is:" +i);
            }
        }
    }
    
}
